-- Baseline: the schema as Hibernate created it up to Milestone 6.

CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120)  NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE api_scans (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         BIGINT       NOT NULL REFERENCES projects (id),
    status             VARCHAR(30)  NOT NULL,
    risk_score         INTEGER,
    endpoint_count     INTEGER,
    open_api_file_name VARCHAR(255),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at       TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT api_scans_status_check
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'))
);

CREATE TABLE findings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id        BIGINT        NOT NULL REFERENCES api_scans (id),
    rule_id        VARCHAR(80)   NOT NULL,
    method         VARCHAR(20)   NOT NULL,
    path           VARCHAR(500)  NOT NULL,
    severity       VARCHAR(20)   NOT NULL,
    issue_type     VARCHAR(80)   NOT NULL,
    title          VARCHAR(160)  NOT NULL,
    description    VARCHAR(1000) NOT NULL,
    recommendation VARCHAR(1000) NOT NULL,
    CONSTRAINT findings_severity_check
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);
